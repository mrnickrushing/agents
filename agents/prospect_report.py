DEFAULT_THEME = (
    "Code quality & robustness",
    "Issues that make the codebase harder to change safely and more likely to break under real-world input.",
)

SEVERITY_ORDER = ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]
SEVERITY_MEANING = {
    "CRITICAL": "exploitable now, or credentials already exposed",
    "HIGH": "a real vulnerability or outage cause; fix soon",
    "MEDIUM": "weakens defences or reliability; schedule it",
    "LOW": "hygiene and hardening",
    "INFO": "worth knowing, no action forced",
}


def summarize(report: Dict[str, Any]) -> Dict[str, Any]:
    """Fold a scan report into theme buckets with real counts and no paths."""
    themes: Dict[str, Dict[str, Any]] = {}
    files_with_findings = set()
    severities: Counter = Counter()

    for entry in report.get("results", []):
        tool = entry.get("tool", "")
        findings = entry.get("result", {}).get("findings", [])
        if not findings:
            continue
        files_with_findings.add(entry.get("file", "?"))
        theme, meaning = THEMES.get(tool, DEFAULT_THEME)
        bucket = themes.setdefault(
            theme,
            {"meaning": meaning, "count": 0, "severities": Counter(), "files": set()},
        )
        for f in findings:
            sev = f.get("severity", "INFO")
            bucket["count"] += 1
            bucket["severities"][sev] += 1
            severities[sev] += 1
        bucket["files"].add(entry.get("file", "?"))

    coverage = report.get("coverage", {}) or {}
    return {
        "themes": themes,
        "severities": severities,
        "files_with_findings": len(files_with_findings),
        "files_scanned": coverage.get("files_scanned") or report.get("files_scanned"),
        "total": sum(severities.values()),
    }


def render_html(
    summary: Dict[str, Any], *, company: str, prepared_by: str = "Rushing Technologies"
) -> str:
    e = html.escape
    sev = summary["severities"]
    now = datetime.now(timezone.utc)

    sev_row = "".join(
        f'<div class="sev"><span class="n">{sev.get(s, 0)}</span><span class="l">{s.title()}</span>'
        f'<span class="m">{e(SEVERITY_MEANING[s])}</span></div>'
        for s in SEVERITY_ORDER
        if sev.get(s)
    )

    theme_blocks = []
    ordered = sorted(
        summary["themes"].items(),
        key=lambda kv: min(
            (SEVERITY_ORDER.index(s) for s in kv[1]["severities"]), default=99
        ),
    )
    for theme, data in ordered:
        counts = ", ".join(
            f"{data['severities'][s]} {s.lower()}"
            for s in SEVERITY_ORDER
            if data["severities"].get(s)
        )
        places = len(data["files"])
        theme_blocks.append(
            f"<section><h2>{e(theme)}</h2>"
            f"<p class='counts'>{data['count']} finding(s) — {e(counts)} — across {places} location(s).</p>"
            f"<p>{e(data['meaning'])}</p></section>"
        )
    if not theme_blocks:
        theme_blocks.append(
            "<section><h2>No findings</h2><p>The automated pass found nothing to flag. That speaks well of the codebase — though automated coverage is a floor, not a ceiling.</p></section>"
        )

    scanned = summary.get("files_scanned")
    scope = (
        f"{scanned} files analysed, findings in {summary['files_with_findings']}."
        if scanned
        else f"Findings in {summary['files_with_findings']} file(s)."
    )

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>{e(company)} — Security &amp; Reliability Snapshot</title>
<style>
  :root{{--ink:#1a1a1a;--muted:#5f6368;--line:#e3e3e3;--accent:#0b5cad;--bg:#fff}}
  @media (prefers-color-scheme:dark){{:root{{--ink:#ececec;--muted:#a0a4a8;--line:#333;--accent:#6db3f2;--bg:#111}}}}
  *{{box-sizing:border-box}} body{{margin:0;background:var(--bg);color:var(--ink);font:16px/1.55 -apple-system,"Segoe UI",Roboto,Helvetica,Arial,sans-serif}}
  main{{max-width:720px;margin:0 auto;padding:48px 24px 64px}}
  header{{border-bottom:2px solid var(--accent);padding-bottom:16px;margin-bottom:12px}}
  h1{{font-size:1.5rem;margin:0 0 4px}} .sub{{color:var(--muted);margin:0}}
  .scope{{color:var(--muted);margin:16px 0 24px}}
  .sevrow{{display:flex;gap:14px;flex-wrap:wrap;margin:0 0 28px}}
  .sev{{border:1px solid var(--line);border-radius:10px;padding:10px 14px;min-width:120px}}
  .sev .n{{font-size:1.4rem;font-weight:700;display:block}} .sev .l{{font-weight:600}}
  .sev .m{{display:block;color:var(--muted);font-size:.8rem;margin-top:2px}}
  section{{margin:0 0 22px;padding-bottom:16px;border-bottom:1px solid var(--line)}}
  section:last-of-type{{border-bottom:0}}
  h2{{font-size:1.05rem;margin:0 0 6px}} .counts{{color:var(--muted);margin:0 0 8px;font-size:.95rem}}
  footer{{color:var(--muted);font-size:.85rem;margin-top:36px;border-top:1px solid var(--line);padding-top:16px}}
</style></head><body><main>
<header><h1>{e(company)}</h1><p class="sub">Security &amp; Reliability Snapshot · {now:%B %Y}</p></header>
<p class="scope">{e(scope)} Automated analysis; exact locations and remediation guidance are provided under an engagement.</p>
<div class="sevrow">{sev_row or '<p>No findings.</p>'}</div>
{"".join(theme_blocks)}
<footer>Prepared by {e(prepared_by)} · generated {now:%Y-%m-%d} · Counts are unmodified scanner output; a section with nothing to report is omitted rather than padded. This snapshot is a starting point, not a completed audit.</footer>
</main></body></html>"""


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Render a scan JSON as a prospect-facing HTML snapshot."
    )
    parser.add_argument(
        "report", help="Path to the JSON written by `agents scan --out`"
    )
    parser.add_argument("--company", required=True, help="Name to put on the document")
    parser.add_argument("--out", help="Output HTML path (default: <report>.html)")
    args = parser.parse_args()

    report = json.loads(Path(args.report).read_text(encoding="utf-8"))
    page = render_html(summarize(report), company=args.company)
    out = Path(args.out or (Path(args.report).with_suffix(".html")))
    out.write_text(page, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

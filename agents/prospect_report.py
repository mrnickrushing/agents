"""Render a scan report as an HTML document a prospect can read.

The scan JSON is written for the operator: rule ids, file paths, line
numbers. Handed to a prospective client it reads as noise — and it also
tells them (and anyone they forward it to) exactly where every weakness is
before any engagement exists. So this renderer is not a reskin; it is an
editorial pass with two audiences in mind:

**The prospect sees categories and consequences, not coordinates.** Findings
are grouped by theme with a plain-language explanation of what each class of
problem costs. Counts and severities are real; file paths and line numbers
are withheld from the shareable body ("3 places" rather than which three).
The full technical detail is what the engagement buys. A teaser that gives
away the map is a free audit, and a teaser that names exact vulnerable lines
in a document designed to be forwarded is a liability for the *prospect*.

**Nothing is inflated.** Every number comes straight off the scan, the
severity scale is printed with its meaning, and a section that found nothing
says so. A lead generated by an exaggerated report becomes a client who
distrusts the first invoice. The honesty rules from the status page apply
here for commercial reasons as much as ethical ones.

Usage (after `agents scan <repo> --out report.json`):

    python -m agents.prospect_report report.json --company "Acme Inc" --out acme.html
"""

